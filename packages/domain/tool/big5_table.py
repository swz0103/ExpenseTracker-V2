"""Writes lib/src/data_exchange/big5_table.dart from Python's cp950 codec.

cp950 is Big5 as Windows writes it, which is what Excel saves a CSV in
on a Traditional Chinese system ("ANSI"). Run from packages/domain:

    python3 tool/big5_table.py

The table lists, for each lead byte 0xA1..0xF9, the characters of its
157 trail bytes (0x40..0x7E, then 0xA1..0xFE), U+FFFD where the code
page has none. The other lead bytes are left to users (EUDC) and hold
nothing in cp950. The file it writes is checked in; run this again only
to rebuild it.
"""

LEADS = range(0xA1, 0xFA)
TRAILS = list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF))
PER_LINE = 40
OUT = 'lib/src/data_exchange/big5_table.dart'


def char(lead, trail):
    try:
        return bytes([lead, trail]).decode('cp950')
    except UnicodeDecodeError:
        return '�'


def literal(c):
    code = ord(c)
    if 0x3400 <= code <= 0x9FFF or 0xF900 <= code <= 0xFAFF:
        return c
    return '\\u%04X' % code


def main():
    chars = [char(lead, trail) for lead in LEADS for trail in TRAILS]
    lines = []
    for i in range(0, len(chars), PER_LINE):
        lines.append("    '%s'" % ''.join(literal(c) for c in chars[i:i + PER_LINE]))
    with open(OUT, 'w', encoding='utf-8') as out:
        out.write(
            '// Generated by tool/big5_table.py from the cp950 code page (Big5 as\n'
            '// Windows writes it); do not edit by hand.\n'
            '// Exception to file length: one table of data.\n'
            '\n'
            '/// The characters of the two-byte Big5 codes: for each lead byte\n'
            '/// 0xA1 to 0xF9, those of its 157 trail bytes (0x40 to 0x7E, then\n'
            '/// 0xA1 to 0xFE), in order; U+FFFD where the code page has none.\n'
            'const big5Characters =\n')
        out.write('\n'.join(lines))
        out.write(';\n')


if __name__ == '__main__':
    main()
